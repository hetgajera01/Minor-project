FEATURE_NAMES = ["N", "P", "K", "temperature", "humidity", "ph", "rainfall"]
MODEL_VERSION = "2.0"


def load_dataset(csv_path=None):
    """Load from CSV if provided and valid, else use embedded data."""
    if csv_path and os.path.isfile(csv_path):
        import csv
        rows = []
        try:
            with open(csv_path, newline="", encoding="utf-8") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    try:
                        rows.append([
                            float(row["N"]), float(row["P"]), float(row["K"]),
                            float(row["temperature"]), float(row["humidity"]),
                            float(row["ph"]), float(row["rainfall"]),
                            row["label"].strip()
                        ])
                    except (ValueError, KeyError):
                        continue
            if len(rows) >= 500:
                print(f"[Dataset] Loaded {len(rows)} rows from {csv_path}")
                return rows
        except Exception as e:
            print(f"[Dataset] Could not read {csv_path}: {e}")

    print(f"[Dataset] Using embedded dataset ({len(FULL_DATASET)} rows)")
    return FULL_DATASET


def prepare_arrays(data):
    X = np.array([[r[0], r[1], r[2], r[3], r[4], r[5], r[6]] for r in data], dtype=float)
    y = np.array([r[7] for r in data])
    return X, y


def deduplicate(X, y):
    """Remove exact duplicate rows."""
    seen = set()
    keep_X, keep_y = [], []
    for xi, yi in zip(X, y):
        key = (tuple(xi), yi)
        if key not in seen:
            seen.add(key)
            keep_X.append(xi)
            keep_y.append(yi)
    X_clean = np.array(keep_X)
    y_clean = np.array(keep_y)
    removed = len(X) - len(X_clean)
    if removed > 0:
        print(f"[Dedup] Removed {removed} duplicate rows. {len(X_clean)} remain.")
    return X_clean, y_clean


def train_and_evaluate(data, output_buf):
    """Full training pipeline with proper held-out evaluation."""
    X, y = prepare_arrays(data)
    X, y = deduplicate(X, y)

    n_samples = len(X)
    n_classes = len(set(y))
    print(f"\n[Data] {n_samples} samples, {n_classes} classes", file=output_buf)
    print(f"[Data] Feature names: {FEATURE_NAMES}", file=output_buf)

    # ── 1. Stratified split: 70% train / 15% val / 15% test ───────────────
    sss1 = StratifiedShuffleSplit(n_splits=1, test_size=0.30, random_state=42)
    for train_idx, temp_idx in sss1.split(X, y):
        X_train, X_temp = X[train_idx], X[temp_idx]
        y_train, y_temp = y[train_idx], y[temp_idx]

    sss2 = StratifiedShuffleSplit(n_splits=1, test_size=0.50, random_state=42)
    for val_idx, test_idx in sss2.split(X_temp, y_temp):
        X_val, X_test = X_temp[val_idx], X_temp[test_idx]
        y_val, y_test = y_temp[val_idx], y_temp[test_idx]

    print(f"\n[Split] Train: {len(X_train)}, Val: {len(X_val)}, Test: {len(X_test)}", file=output_buf)

    # ── 2. Baseline model ─────────────────────────────────────────────────
    baseline = DummyClassifier(strategy="most_frequent", random_state=42)
    baseline.fit(X_train, y_train)
    baseline_acc = accuracy_score(y_test, baseline.predict(X_test))
    print(f"\n[Baseline] Most-frequent class accuracy on test set: {baseline_acc*100:.1f}%", file=output_buf)

    # ── 3. Candidate: Random Forest ───────────────────────────────────────
    rf_pipeline = Pipeline([
        ("scaler", StandardScaler()),
        ("clf", RandomForestClassifier(
            n_estimators=300,
            max_depth=None,
            min_samples_split=2,
            min_samples_leaf=1,
            random_state=42,
            n_jobs=-1,
        )),
    ])
    rf_pipeline.fit(X_train, y_train)
    rf_val_acc  = accuracy_score(y_val,  rf_pipeline.predict(X_val))
    rf_test_acc = accuracy_score(y_test, rf_pipeline.predict(X_test))
    rf_test_f1  = f1_score(y_test, rf_pipeline.predict(X_test), average="macro", zero_division=0)
    print(f"\n[RandomForest] Val accuracy:  {rf_val_acc*100:.1f}%", file=output_buf)
    print(f"[RandomForest] Test accuracy: {rf_test_acc*100:.1f}%  (HELD-OUT)", file=output_buf)
    print(f"[RandomForest] Test macro-F1: {rf_test_f1*100:.1f}%  (HELD-OUT)", file=output_buf)

    # ── 4. Full classification report on test set ─────────────────────────
    y_pred_test = rf_pipeline.predict(X_test)
    report = classification_report(y_test, y_pred_test, zero_division=0)
    print(f"\n[Classification Report — TEST SET]\n{report}", file=output_buf)

    # ── 5. Confusion matrix (compact) ────────────────────────────────────
    classes = sorted(set(y))
    cm = confusion_matrix(y_test, y_pred_test, labels=classes)
    print("[Confusion Matrix — TEST SET]", file=output_buf)
    print("Classes (in order):", classes, file=output_buf)
    print(cm, file=output_buf)

    # ── 6. Retrain on train+val for final model ───────────────────────────
    X_trainval = np.vstack([X_train, X_val])
    y_trainval = np.concatenate([y_train, y_val])
    final_pipeline = Pipeline([
        ("scaler", StandardScaler()),
        ("clf", RandomForestClassifier(
            n_estimators=300,
            max_depth=None,
            min_samples_split=2,
            min_samples_leaf=1,
            random_state=42,
            n_jobs=-1,
        )),
    ])
    final_pipeline.fit(X_trainval, y_trainval)

    metrics = {
        "baseline_test_accuracy": round(baseline_acc, 4),
        "rf_val_accuracy":        round(rf_val_acc, 4),
        "rf_test_accuracy":       round(rf_test_acc, 4),
        "rf_test_macro_f1":       round(rf_test_f1, 4),
        "n_train": int(len(X_trainval)),
        "n_test":  int(len(X_test)),
        "n_classes": int(n_classes),
        "classes":   sorted(set(y)),
    }
    return final_pipeline, metrics


def save_outputs(pipeline, metrics, report_str):
    """Persist model + metadata + report."""
    # Delete stale model so inference always uses the new one
    if os.path.exists(MODEL_PATH):
        os.remove(MODEL_PATH)
    joblib.dump(pipeline, MODEL_PATH)
    print(f"\n[Model] Saved to {MODEL_PATH}")

    meta = {
        "model_version":   MODEL_VERSION,
        "trained_at":      datetime.datetime.utcnow().isoformat() + "Z",
        "dataset":         "Kaggle Crop Recommendation Dataset (CC0) — embedded/expanded",
        "dataset_url":     "https://www.kaggle.com/datasets/atharvaingle/crop-recommendation-dataset",
        "features":        FEATURE_NAMES,
        "algorithm":       "RandomForestClassifier (n_estimators=300, sklearn Pipeline with StandardScaler)",
        "split":           "Stratified 70/15/15 (train/val/test)",
        "evaluation_note": "All metrics computed on held-out test set ONLY. Train data never used for evaluation.",
        "metrics":         metrics,
        "limitations": [
            "Location (state) and season are NOT model features — this dataset does not include them.",
            "Predictions are soil+weather suitability scores, NOT calibrated success probabilities.",
            "The dataset represents average Indian agronomic conditions, not Gujarat-specific data.",
            "Financial estimates are reference values, not ML predictions.",
        ]
    }
    with open(META_PATH, "w") as f:
        json.dump(meta, f, indent=2)
    print(f"[Meta] Saved to {META_PATH}")

    with open(REPORT_PATH, "w") as f:
        f.write(report_str)
    print(f"[Report] Saved to {REPORT_PATH}")


def main():
    parser = argparse.ArgumentParser(description="Train AgriBudget Crop Recommendation model")
    parser.add_argument("--csv", default=None, help="Path to Kaggle crop recommendation CSV (optional)")
    args = parser.parse_args()

    print("=" * 60)
    print("  AgriBudget — Crop Recommendation Training Pipeline")
    print(f"  Model version: {MODEL_VERSION}")
    print("=" * 60)

    data = load_dataset(args.csv)

    buf = io.StringIO()
    pipeline, metrics = train_and_evaluate(data, buf)
    report_str = buf.getvalue()

    # Echo to console
    print(report_str)

    save_outputs(pipeline, metrics, report_str)

    print("\n" + "=" * 60)
    print("  Training complete.")
    print(f"  Test accuracy (held-out): {metrics['rf_test_accuracy']*100:.1f}%")
    print(f"  Test macro-F1 (held-out): {metrics['rf_test_macro_f1']*100:.1f}%")
    print(f"  Baseline accuracy:        {metrics['baseline_test_accuracy']*100:.1f}%")
    print("=" * 60)
    return 0


if __name__ == "__main__":
    sys.exit(main())
